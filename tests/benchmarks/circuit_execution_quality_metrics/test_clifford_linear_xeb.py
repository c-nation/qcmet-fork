import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[3]))

from qiskit import QuantumCircuit
from qiskit.exceptions import QiskitError
from qiskit.quantum_info import Clifford

from qcmet.benchmarks.circuit_execution_quality_metrics.clifford_linear_xeb import (
    CliffordLinearXEB,
)


def is_clifford(circuit):
    """Return whether the circuit is Clifford-compatible."""
    try:
        Clifford.from_circuit(circuit)
        return True
    except QiskitError:
        return False


def test_build_circuit_structure():
    """Test the structure of circuits generated by build_circuit()."""
    n_qubits = 6
    max_depth = 3
    for d in range(1, max_depth + 1):
        clifford_linear_xeb_instance = CliffordLinearXEB(
            qubits=n_qubits, depth=d, num_circuits=1, seed=42
        )
        circuit = clifford_linear_xeb_instance.build_circuit(
            num_qubits=n_qubits, depth=d
        )
        assert isinstance(circuit, QuantumCircuit)
        assert circuit.num_qubits == n_qubits
        # Check that the number of layers is as expected (depth * 4 for single + entangling)
        assert is_clifford(circuit), f"Circuit at depth {d} is not a Clifford circuit."


def test_xeb_known_circuit():
    """Test XEB fidelity for a deterministic four-qubit |0000> circuit."""
    n_qubits = 4
    circuit = QuantumCircuit(n_qubits)
    experiment = CliffordLinearXEB(
        qubits=n_qubits,
        depth=1,
        num_circuits=1,
        seed=123,
    )

    fidelity = experiment._cross_entropy_fidelity(
        circuit,
        {"0000": 500},
    )

    assert fidelity == 2**n_qubits - 1
